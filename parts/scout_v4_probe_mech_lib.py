"""Scout v4 probe: the drawn mechanism parts' shared geometry (10 Nov, Spark: "start printing the parts needed for the bench test").
Not topology: each part is one make.py (parts/scout_v4_probe_spool, _pinion, _roller, _bench_base, _coupon) built from this.

Gears: module 0.8, 20 deg, generated by rolling a rack cutter over the blank (shapely), so the flanks are true involutes with
the root the cutter leaves. The 12 T pinion is undercut at x = 0 (z < 17), so the pair is profile-shifted +0.35 / -0.35: the
centre distance stays 20.8 (tools/scout_v4_shape.GEAR), the pinion's root thickens and its tip stays 0.25 m wide.
Print clearances (Bambu A1 mini, PCTG, 0.4 nozzle, 0.16 layers; E until the coupon is read):
  - BACKLASH 0.15 a gear on the pitch circle (0.3 in the pair): FDM flanks are ~0.05-0.1 proud and the turret's bores ~0.1 off
  - holes print ~0.1 under: the spool's bore 3.4 runs free on an M3 (2.9 real); the D bore 3.1 / 2.6 across the flat grips
    the N20's 3.0 / 2.5 shaft (press, then a drop of CA); the MR63ZZ seats 6.05 for a light press of the 6.0 race
  parts/scout_v4_probe_coupon prints every one of these in three sizes, and the pair on 20.8 / 20.9 / 21.0 centres."""
import math, os, sys
import numpy as np, trimesh
from shapely.geometry import Point, Polygon, box as sbox
from shapely.ops import unary_union
from shapely import affinity

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import scout_v4_shape as S                                                       # noqa: E402

M, ALPHA = S.GEAR["m"], math.radians(20.0)
SHIFT = {"spool": -0.35, "pinion": 0.35}
BACKLASH = 0.15
PCTG = 1.23                                                                       # g/cm3 (topo/material.py)


def gear_2d(z, x=0.0, m=M, backlash=BACKLASH, res=160):
    """the gear's outline (shapely, centre at 0): a blank of radius r + (1 + x) m less the rack cutter rolled over it"""
    r = z * m / 2; ra = r + (1 + x) * m; pl = r + x * m
    s = math.pi * m / 2 + backlash / 2                                            # the cutter's tooth at its pitch line (wider: thinner gear teeth)
    t = math.tan(ALPHA)
    tooth = Polygon([(-(s / 2 - 1.25 * m * t), pl - 1.25 * m), (s / 2 - 1.25 * m * t, pl - 1.25 * m),
                     (s / 2 + 2.0 * m * t, pl + 2.0 * m), (-(s / 2 + 2.0 * m * t), pl + 2.0 * m)])
    phm = 3.2 * m / r
    cuts = []
    for ph in np.linspace(-phm, phm, res):
        c = affinity.translate(tooth, xoff=-r * ph)                                 # the rack rolls with the pitch circle (no slip)
        cuts.append(affinity.rotate(c, -ph, origin=(0, 0), use_radians=True))
    space = unary_union(cuts)
    spaces = unary_union([affinity.rotate(space, 360.0 * k / z, origin=(0, 0)) for k in range(z)])
    g = Point(0, 0).buffer(ra, 256).difference(spaces)
    return g.buffer(0.02).buffer(-0.02)                                           # drop the cutter's facets' slivers


def extrude(poly, z0, z1):
    """a shapely polygon extruded along z from z0 to z1 (trimesh)"""
    m = trimesh.creation.extrude_polygon(poly, z1 - z0)
    m.apply_translation([0, 0, z0]); return m


def cyl(r, z0, z1, x=0.0, y=0.0, n=96):
    return extrude(Point(x, y).buffer(r, n), z0, z1)


def boolean(a, b, op):
    import manifold3d as mf
    def man(t):
        return mf.Manifold(mf.Mesh(np.asarray(t.vertices, np.float32), np.asarray(t.faces, np.uint32)))
    A = man(a); B = man(b)
    R = A + B if op == "+" else A - B
    o = R.to_mesh(); return trimesh.Trimesh(np.asarray(o.vert_properties)[:, :3], np.asarray(o.tri_verts), process=True)


def union(ms):
    out = ms[0]
    for m in ms[1:]:
        out = boolean(out, m, "+")
    return out


def minus(a, ms):
    out = a
    for m in ms:
        out = boolean(out, m, "-")
    return out


def to_drone(m, cx, cz):
    """a part laid out with its axis along local z, to the drone frame: local z -> drone y, local y -> drone -z, at (cx, ., cz)"""
    d = m.copy()
    d.apply_transform(trimesh.transformations.rotation_matrix(-math.pi / 2, [1, 0, 0]))
    d.apply_translation([cx, 0, cz]); return d


def save(name, m_print, m_drone, note):
    """parts/<name>/part.stl in the drone's frame (the page, the shape tool's checks), print/<name>.stl laid flat for the A1 mini;
    the solid check on the print mesh; one line"""
    assert m_print.is_watertight and m_print.is_volume, name
    d = os.path.join(ROOT, "parts", name); os.makedirs(d, exist_ok=True)
    m_drone.export(os.path.join(d, "part.stl"))
    os.makedirs(os.path.join(ROOT, "print"), exist_ok=True)
    p = os.path.join(ROOT, "print", f"{name}.stl"); m_print.export(p)
    import subprocess
    sc = subprocess.run([sys.executable, os.path.join(ROOT, "tools", "solid_check.py"), p], capture_output=True, text=True)
    ok = "PASS" if sc.returncode == 0 else "FAIL"
    v = m_print.volume / 1000
    print(f"{name}: {v:.2f} cm3, {v * PCTG:.1f} g PCTG, {np.round(m_print.extents, 1).tolist()} mm as printed, solid check {ok}; {note}")
    if ok == "FAIL":
        print(sc.stdout[-1500:], sc.stderr[-800:])
    return ok
